import type { Locale } from "@/lib/i18n";

/**
 * The privacy notice (GDPR Art. 13). The deploying organisation is the
 * controller, so its name, contact and legal basis come from the deployment.
 * Until they are set the page says it is a draft and shows no invented details.
 */
export type PrivacySection = { heading: string; text?: string; items?: string[] };

export type PrivacyNotice = {
  title: string;
  draftNote: string | null;
  sections: PrivacySection[];
  back: string;
};

type Env = Record<string, string | undefined>;

const setting = (env: Env, name: string) => env[name]?.trim() || null;

export function privacyNotice(locale: Locale, env: Env = process.env): PrivacyNotice {
  const controller = setting(env, "WIZARD_PRIVACY_CONTROLLER");
  const contact = setting(env, "WIZARD_PRIVACY_CONTACT");
  const legalBasis = setting(env, "WIZARD_PRIVACY_LEGAL_BASIS");
  const complete = Boolean(controller && contact && legalBasis);

  if (locale === "en") {
    const pending = "To be confirmed by the organisation running this service.";
    return {
      title: "Privacy notice",
      back: "Back",
      draftNote: complete
        ? null
        : "This is a draft. The organisation running this service confirms the missing details before production use.",
      sections: [
        {
          heading: "Controller and contact",
          items: [`Controller: ${controller ?? pending}`, `Contact: ${contact ?? pending}`],
        },
        {
          heading: "What is processed",
          items: [
            "Your account email address",
            "Chat messages and use case descriptions",
            "Documents and cases you upload",
            "Generated packages and run results",
            "Technical logs",
          ],
        },
        {
          heading: "Purpose and legal basis",
          text: `The data is used only to design and test your solution. Legal basis: ${legalBasis ?? pending}`,
        },
        {
          heading: "AI processing",
          text: "You talk to an AI assistant, and its answers and drafts are generated by AI. Your messages and documents are sent to the AI model provider configured for this service. The service makes no automated decisions about you.",
        },
        {
          heading: "Recipients and location",
          text: "The application and its data run on CSC's Rahti and Allas services in Finland. Model calls go to the provider configured for this service, which processes them under a data processing agreement. The region of the model service is confirmed by the organisation running this service.",
        },
        {
          heading: "How long data is kept",
          text: "A session and its files are kept until they are deleted. Finished sandbox runs and their logs are removed from the cluster after one hour. Retention periods for sessions, uploads and logs are confirmed by the organisation running this service.",
        },
        {
          heading: "Your rights",
          items: [
            "You can delete your own session from the session list. It cannot be undone.",
            "You can ask for access to your data, and for it to be corrected, erased, restricted or transferred, and you can object to its processing. Use the contact above.",
            "You can complain to the supervisory authority. In Finland it is the Data Protection Ombudsman.",
          ],
        },
        {
          heading: "Please use synthetic data",
          text: "Do not upload personal data or confidential documents unless they are needed. Use synthetic or anonymised material where you can.",
        },
      ],
    };
  }

  const pending = "Palvelua ylläpitävä organisaatio vahvistaa tämän.";
  return {
    title: "Tietosuojaseloste",
    back: "Takaisin",
    draftNote: complete
      ? null
      : "Tämä on luonnos. Palvelua ylläpitävä organisaatio vahvistaa puuttuvat tiedot ennen tuotantokäyttöä.",
    sections: [
      {
        heading: "Rekisterinpitäjä ja yhteystiedot",
        items: [`Rekisterinpitäjä: ${controller ?? pending}`, `Yhteystieto: ${contact ?? pending}`],
      },
      {
        heading: "Mitä tietoja käsitellään",
        items: [
          "Käyttäjätilisi sähköpostiosoite",
          "Keskusteluviestit ja käyttötapausten kuvaukset",
          "Lataamasi dokumentit ja tapaukset",
          "Tuotetut paketit ja ajojen tulokset",
          "Tekniset lokit",
        ],
      },
      {
        heading: "Käsittelyn tarkoitus ja oikeusperuste",
        text: `Tietoja käytetään vain ratkaisusi suunnitteluun ja testaamiseen. Oikeusperuste: ${legalBasis ?? pending}`,
      },
      {
        heading: "Tekoälyn käyttö",
        text: "Keskustelet tekoälyavustajan kanssa, ja sen vastaukset ja luonnokset ovat tekoälyn tuottamia. Viestisi ja dokumenttisi lähetetään palveluun määritetylle tekoälymallin tarjoajalle. Palvelu ei tee sinua koskevia automaattisia päätöksiä.",
      },
      {
        heading: "Vastaanottajat ja sijainti",
        text: "Sovellus ja sen data toimivat CSC:n Rahti- ja Allas-palveluissa Suomessa. Mallikutsut menevät palveluun määritetylle tarjoajalle, joka käsittelee niitä tietojenkäsittelysopimuksen mukaisesti. Palvelua ylläpitävä organisaatio vahvistaa mallipalvelun alueen.",
      },
      {
        heading: "Kuinka kauan tietoja säilytetään",
        text: "Sessio ja sen tiedostot säilyvät, kunnes ne poistetaan. Valmiit sandbox-ajot ja niiden lokit poistuvat klusterista tunnin kuluttua. Palvelua ylläpitävä organisaatio vahvistaa sessioiden, latausten ja lokien säilytysajat.",
      },
      {
        heading: "Oikeutesi",
        items: [
          "Voit poistaa oman sessiosi session listalta. Poistoa ei voi perua.",
          "Voit pyytää pääsyä tietoihisi sekä niiden oikaisua, poistamista, käsittelyn rajoittamista tai siirtämistä, ja voit vastustaa käsittelyä. Käytä yllä olevaa yhteystietoa.",
          "Voit tehdä valituksen valvontaviranomaiselle. Suomessa se on tietosuojavaltuutetun toimisto.",
        ],
      },
      {
        heading: "Käytä synteettistä aineistoa",
        text: "Älä lataa henkilötietoja tai luottamuksellisia dokumentteja, ellei se ole tarpeen. Käytä synteettistä tai anonymisoitua aineistoa aina kun voit.",
      },
    ],
  };
}
